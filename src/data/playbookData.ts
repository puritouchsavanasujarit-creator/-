export interface ShippingCalculation {
  fee: number;
  isFree: boolean;
  freeThreshold: number | null;
  etaText: string;
  messengerTravelText: string;
  requiresOpCheck: boolean;
  notes: string[];
}

export function calculateShipping(params: {
  distanceKm: number;
  orderSubtotal: number;
  isUrgentUnder2Hr?: boolean;
  isUpcountryInterExpress?: boolean;
  isSaturdayDispatch?: boolean;
}): ShippingCalculation {
  const {
    distanceKm,
    orderSubtotal,
    isUrgentUnder2Hr = false,
    isUpcountryInterExpress = false,
    isSaturdayDispatch = false,
  } = params;

  if (isUpcountryInterExpress) {
    const notes = [
      'ส่งต่างจังหวัดด้วยรถห้องเย็น Inter Express ค่าบริการ 450 บาท/ชิ้น',
      'ใช้เวลานับถอยหลัง 3 วัน และตัดรอบก่อน 12.00 น.',
    ];
    if (isSaturdayDispatch) {
      notes.push('ข้อควรระวัง: รถห้องเย็น Inter Express งดวิ่งวันเสาร์ ต้องเลื่อนรอบส่งเป็นวันทำการถัดไป');
    }
    return {
      fee: 450,
      isFree: false,
      freeThreshold: null,
      etaText: 'นับถอยหลัง 3 วัน (ตัดรอบก่อน 12.00 น. · งดวิ่งวันเสาร์)',
      messengerTravelText: 'รถห้องเย็น Inter Express',
      requiresOpCheck: true,
      notes,
    };
  }

  const km = Math.max(1, distanceKm);
  let baseFee = 59;
  let freeThreshold: number | null = 1500;
  let etaText = 'ภายใน 1–1.5 ชม.';
  let messengerTravelText = '20–30 นาที';
  const notes: string[] = [];

  if (km <= 10) {
    baseFee = 59;
    freeThreshold = 1500;
    etaText = 'ภายใน 1–1.5 ชม.';
    messengerTravelText = '20–30 นาที';
  } else if (km <= 25) {
    baseFee = 159;
    freeThreshold = 4000;
    etaText = km <= 20 ? 'ภายใน 2 ชม.' : 'ภายใน 2.5 ชม.';
    messengerTravelText = km <= 20 ? '40 นาที' : '40–50 นาที';
  } else {
    const extraKm = km - 25;
    baseFee = 159 + extraKm * 10;
    freeThreshold = null;
    etaText = 'ภายใน 3 ชม. (แล้วแต่พิจารณา)';
    messengerTravelText = '60–90 นาที';
    notes.push(`ระยะทางเกิน 25 กม. คิดเพิ่ม 10 บาท/กม. ส่วนเกิน (${extraKm} กม. × 10 = ${extraKm * 10} บาท)`);
  }

  const isFree = freeThreshold !== null && orderSubtotal >= freeThreshold;
  const finalFee = isFree ? 0 : baseFee;

  if (isFree && freeThreshold !== null) {
    notes.push(`ยอดสั่งซื้อ ${orderSubtotal.toLocaleString()} บาท ถึงเกณฑ์ส่งฟรี (${freeThreshold.toLocaleString()} บาทขึ้นไป)`);
  } else if (freeThreshold !== null) {
    const diff = freeThreshold - orderSubtotal;
    notes.push(`เพิ่มอีก ${diff.toLocaleString()} บาท เพื่อรับสิทธิ์ส่งฟรี (เกณฑ์ ${freeThreshold.toLocaleString()} บาท)`);
  }

  let requiresOpCheck = isUrgentUnder2Hr || km >= 30;
  if (isUrgentUnder2Hr) {
    notes.push('เคสเร่งด่วนน้อยกว่า 2 ชม. หรือชุดส่งด่วน 1–1.5 ชม. (ไม่เกิน 25 กม.): ต้องประสานทีม OP ประเมินความพร้อมก่อนรับปากลูกค้าเสมอ');
  }

  return {
    fee: finalFee,
    isFree,
    freeThreshold,
    etaText,
    messengerTravelText,
    requiresOpCheck,
    notes,
  };
}

